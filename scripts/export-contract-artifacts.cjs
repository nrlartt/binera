const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const artifactDir = path.join(root, ".hardhat", "artifacts", "contracts");
const names = ["BineraStake", "BineraReputation", "BineraArbitration", "BineraBountyVault"];

const out = {};
for (const name of names) {
  const file = path.join(artifactDir, `${name}.sol`, `${name}.json`);
  if (!fs.existsSync(file)) throw new Error(`Missing artifact: ${file}. Run npm run compile:contracts first.`);
  const artifact = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!artifact.abi || !artifact.bytecode || artifact.bytecode === "0x") throw new Error(`Incomplete artifact: ${name}`);
  out[name] = { abi: artifact.abi, bytecode: artifact.bytecode };
}

const target = path.join(root, "src", "lib", "contracts", "artifacts.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
const body = `// Generated by scripts/export-contract-artifacts.cjs. Do not edit by hand.\n// Source: contracts/*.sol compiled with Hardhat (solc 0.8.24, optimizer 200).\n\nexport const contractArtifacts = ${JSON.stringify(out, null, 2)} as const;\n\nexport type ContractName = keyof typeof contractArtifacts;\n`;
fs.writeFileSync(target, body, "utf8");
console.log(`Wrote ${target} (${names.length} contracts, ${Math.round(body.length / 1024)} KiB).`);
